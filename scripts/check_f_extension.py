def check_fa_counts(fa: list[dict], stats: dict, manifest: dict, corpus: list[dict],
                    corpus_by_id: dict, negatives_by_id: dict) -> list[str]:
    bad = []
    statuses = Counter(row.get("answer_key_status") for row in fa)
    by_split = Counter(row.get("split") for row in fa)
    fa_stats = stats.get("fa") or {}
    entry = (manifest.get("tasks") or {}).get(FA_NAME) or {}
    if fa_stats.get("rows") != len(fa):
        bad.append(f"stats fa.rows = {fa_stats.get('rows')} but F-A has {len(fa)} rows")
    if fa_stats.get("scorable_rows") != statuses.get("labeled", 0):
        bad.append(f"stats fa.scorable_rows = {fa_stats.get('scorable_rows')} but "
                   f"{statuses.get('labeled', 0)} rows are labeled")
    if fa_stats.get("by_answer_key_status") != dict(statuses):
        bad.append(f"stats fa.by_answer_key_status {fa_stats.get('by_answer_key_status')} "
                   f"but the rows give {dict(statuses)}")
    if fa_stats.get("by_split") != dict(by_split):
        bad.append(f"stats fa.by_split {fa_stats.get('by_split')} but the rows give "
                   f"{dict(by_split)}")
    if fa_stats.get("unique_source_records") != len({(r.get("source") or {})
                                                     .get("record_id") for r in fa}):
        bad.append("stats fa.unique_source_records disagrees with the recount of the rows")
    expected_rows = len({fid for fid in corpus_by_id if fid in negatives_by_id})
    if len(fa) != expected_rows:
        bad.append(f"F-A has {len(fa)} rows but the canonical layers support "
                   f"{expected_rows}")
    if stats.get("corpus_records") != len(corpus):
        bad.append(f"stats.corpus_records = {stats.get('corpus_records')} but the corpus "
                   f"has {len(corpus)}")
    axes_supported = Counter()
    assessable = Counter()
    for row in fa:
        for axis, value in (row.get("answer_key", {}).get("axes") or {}).items():
            if value == "supported":
                axes_supported[axis] += 1
        for axis in row.get("assessed_axes") or []:
            assessable[axis] += 1
    if fa_stats.get("axes_supported") != dict(axes_supported):
        bad.append(f"stats fa.axes_supported {fa_stats.get('axes_supported')} but the rows "
                   f"give {dict(axes_supported)}")
    if fa_stats.get("assessability") != dict(assessable):
        bad.append(f"stats fa.assessability {fa_stats.get('assessability')} but the rows "
                   f"give {dict(assessable)}")
    if fa_stats.get("technical_explanation_rows") != sum(
            1 for row in fa if row.get("answer_key", {}).get("technical_explanation_axes")):
        bad.append("stats fa.technical_explanation_rows disagrees with the rows")
    for axis, metrics in (fa_stats.get("per_axis_metrics") or {}).items():
        values = [row["answer_key"]["axes"].get(axis) for row in fa
                  if axis in (row.get("assessed_axes") or [])]
        if not values:
            if metrics.get("coverage") != 0:
                bad.append(f"stats per_axis_metrics {axis} reports coverage for no row")
            continue
        supported = sum(1 for v in values if v == "supported")
        unknown = sum(1 for v in values if v == "unknown")
        if metrics.get("coverage") != len(values):
            bad.append(f"stats per_axis_metrics {axis} coverage "
                       f"{metrics.get('coverage')} but the rows give {len(values)}")
        if metrics.get("supported_rate") != round(supported / len(values), 4):
            bad.append(f"stats per_axis_metrics {axis} supported_rate "
                       f"{metrics.get('supported_rate')} is not {supported}/{len(values)}")
        if metrics.get("unknown_rate") != round(unknown / len(values), 4):
            bad.append(f"stats per_axis_metrics {axis} unknown_rate is not a recount")
    if (entry.get("tasks") != len(fa) or entry.get("labeled") != statuses.get("labeled", 0)
            or entry.get("partial") != statuses.get("partial", 0)
            or entry.get("unlabeled") != statuses.get("unlabeled", 0)):
        bad.append(_manifest_status_line(FA_NAME, entry, statuses, len(fa)))
    if entry.get("by_split") != dict(by_split):
        bad.append(f"manifest {FA_NAME} by_split {entry.get('by_split')} but the rows give "
                   f"{dict(by_split)}")
    if entry.get("scorable") != statuses.get("labeled", 0) \
            or entry.get("unscorable") != len(fa) - statuses.get("labeled", 0):
        bad.append(f"manifest {FA_NAME} scorable/unscorable is not the recount of labeled rows")
    if entry.get("file") != f"benchmark/{FA_NAME}.jsonl":
        bad.append(f"manifest {FA_NAME} file entry is {entry.get('file')!r}")
    if not str(stats.get("non_additivity") or "").strip():
        bad.append("stats drop the non_additivity note: axis totals overlap and must not be "
                   "reported as a sum")
    return bad


def check_fb_counts(fb: list[dict], stats: dict, manifest: dict,
                    negatives_by_id: dict, findings_by_id: dict) -> list[str]:
    bad = []
    fb_stats = stats.get("fb") or {}
    entry = (manifest.get("tasks") or {}).get(FB_NAME) or {}
    classes = Counter((row.get("answer_key") or {}).get("relationship") for row in fb)
    by_split = Counter(row.get("split") for row in fb)
    statuses = Counter(row.get("answer_key_status") for row in fb)
    unique_cands = {(row.get("source") or {}).get("candidate_record_id") for row in fb}
    unique_comps = {(row.get("source") or {}).get("comparison_record_id") for row in fb
                    if (row.get("source") or {}).get("comparison_record_id") != "unresolved"}
    if fb_stats.get("pair_rows") != len(fb):
        bad.append(f"stats fb.pair_rows = {fb_stats.get('pair_rows')} but F-B has "
                   f"{len(fb)} rows")
    if fb_stats.get("by_relationship") != dict(classes):
        bad.append(f"stats fb.by_relationship {fb_stats.get('by_relationship')} but the rows "
                   f"give {dict(classes)}")
    if fb_stats.get("by_split") != dict(by_split):
        bad.append(f"stats fb.by_split {fb_stats.get('by_split')} but the rows give "
                   f"{dict(by_split)}")
    if fb_stats.get("unique_candidate_submissions") != len(unique_cands):
        bad.append(f"stats fb.unique_candidate_submissions = "
                   f"{fb_stats.get('unique_candidate_submissions')} but the rows back "
                   f"{len(unique_cands)} submissions")
    if fb_stats.get("unique_canonical_findings") != len(unique_comps):
        bad.append(f"stats fb.unique_canonical_findings = "
                   f"{fb_stats.get('unique_canonical_findings')} but the rows name "
                   f"{len(unique_comps)} findings")
    if fb_stats.get("confirmed_duplicate_pairs") != classes.get("same_vulnerability", 0):
        bad.append("stats fb.confirmed_duplicate_pairs is not the same_vulnerability recount")
    if fb_stats.get("rule_derived_distinct_pairs") != classes.get("distinct_vulnerability", 0):
        bad.append("stats fb.rule_derived_distinct_pairs is not the distinct recount")
    if fb_stats.get("ambiguous_class_pairs") != classes.get("ambiguous", 0):
        bad.append("stats fb.ambiguous_class_pairs is not the ambiguous recount")
    if fb_stats.get("ambiguous_unscorable_pairs") != statuses.get("unlabeled", 0):
        bad.append("stats fb.ambiguous_unscorable_pairs is not the unlabeled recount")
    if sum(classes.values()) != len(fb):
        bad.append("F-B relationship classes do not sum to the row count")
    excluded = fb_stats.get("excluded_pairs")
    if not isinstance(excluded, dict):
        bad.append("stats fb.excluded_pairs is missing")
    else:
        for reason, count in excluded.items():
            if reason not in FB_EXCLUSION_REASONS:
                bad.append(f"stats fb.excluded_pairs records unknown reason {reason!r}")
            if not isinstance(count, int) or count < 0:
                bad.append(f"stats fb.excluded_pairs[{reason}] = {count!r} is not a count")
    if (entry.get("tasks") != len(fb) or entry.get("labeled") != statuses.get("labeled", 0)
            or entry.get("partial") != statuses.get("partial", 0)
            or entry.get("unlabeled") != statuses.get("unlabeled", 0)):
        bad.append(_manifest_status_line(FB_NAME, entry, statuses, len(fb)))
    if entry.get("by_split") != dict(by_split):
        bad.append(f"manifest {FB_NAME} by_split {entry.get('by_split')} but the rows give "
                   f"{dict(by_split)}")
    if entry.get("scorable") != statuses.get("labeled", 0):
        bad.append(f"manifest {FB_NAME} scorable is not the labeled recount")
    if entry.get("file") != f"benchmark/{FB_NAME}.jsonl":
        bad.append(f"manifest {FB_NAME} file entry is {entry.get('file')!r}")
    # every candidate must be a real submission, every comparison a real finding
    for cid in unique_cands:
        if cid not in negatives_by_id:
            bad.append(f"F-B candidate {cid} is not a negative_findings record")
    for tid in unique_comps:
        if tid not in findings_by_id:
            bad.append(f"F-B comparison {tid} is not a findings record")
    return bad


def check_fb_exclusion_rule(fb: list[dict], corpus: list[dict], negatives_by_id: dict,
                            findings_by_id: dict) -> list[str]:
    """Every proposed positive/ambiguous pair is shipped or dropped for a judgement phrase.

    The drop counters for the distinct pool need the builder's candidate ranking, so
    the number itself is checked for shape in `check_fb_counts` and the rule is
    checked here over the pools that the canonical layers define exactly.
    """
    bad = []
    shipped = {(row.get("source") or {}).get("candidate_record_id")
               for row in fb if (row.get("source") or {}).get("comparison_record_id")
               != "unresolved"}
    proposed: dict[str, list[str]] = {}
    for record in corpus:
        fid = record.get("finding_id")
        negative = negatives_by_id.get(fid)
        if negative is None:
            continue
        methods = (record.get("axes") or {}).get("duplicate_corroboration") or {}
        targets = set()
        for method in methods.get("methods") or []:
            target = method.get("corroborating_finding")
            if method.get("method") == "explicit_duplicate_of_pointer" and target:
                targets.add(target)
            elif method.get("method") == "same_code_target_same_audit" \
                    and target in findings_by_id:
                targets.add(target)
        if targets:
            proposed[fid] = sorted(targets)
    for cid, targets in proposed.items():
        if cid in shipped:
            continue
        negative = negatives_by_id[cid]
        texts = [value for value in ((negative.get("finding") or {}).get("title"),
                                     (negative.get("negative_analysis") or {})
                                     .get("why_it_looked_plausible"),
                                     (negative.get("security_reasoning") or {})
                                     .get("broken_behavior"))
                 if isinstance(value, str)]
        target_texts = []
        for tid in targets:
            finding = findings_by_id.get(tid) or {}
            target_texts += [value for value in (
                (finding.get("finding") or {}).get("title"),
                (finding.get("security_reasoning") or {}).get("broken_behavior"))
                if isinstance(value, str)]
        if fx.leak_free(*texts, *target_texts):
            bad.append(f"F-B candidate {cid} proposes {targets}, is leak-free, but no pair "
                       "row was emitted and none is recorded as excluded")
    return bad


PROHIBITED_PROSE = (
    re.compile(r"(?P<n>\d+)\s+(?:independent|distinct|separate)\s+(?:tasks?|examples?|"
               r"samples?|records?)", re.IGNORECASE),
    re.compile(r"pairs?[^.\n]{0,60}\b(?:independently|as independent)\b", re.IGNORECASE),
)


def check_prose(md: str, stats: dict) -> list[str]:
    """Invariant 11: the pair count is never prose that reads as independent submissions."""
    bad = []
    if not md.strip():
        return ["reports/f_extension.md is missing or empty"]
    fa, fb_stats = stats.get("fa") or {}, stats.get("fb") or {}
    for number, label in ((fb_stats.get("pair_rows"), "pairs"),
                          (fa.get("rows"), "task rows")):
        if str(number) not in md:
            bad.append(f"reports/f_extension.md no longer states {label} = {number}")
    pair_rows = fb_stats.get("pair_rows") or 0
    unique = fb_stats.get("unique_candidate_submissions") or 0
    if str(unique) not in md:
        bad.append("reports/f_extension.md does not report the unique candidate "
                   "submissions backing the pairs, so the pair count could be read as "
                   "a count of independent submissions")
    if pair_rows > unique and not re.search(r"\bpairs?\b", md, re.IGNORECASE):
        bad.append(f"reports/f_extension.md reports {pair_rows} pairs over {unique} "
                   "submissions without calling them pairs")
    for line in md.splitlines():
        for pattern in PROHIBITED_PROSE:
            match = pattern.search(line)
            if match:
                bad.append(f"reports/f_extension.md calls {match.group(0)!r} a count of "
                           f"independent tasks; pairs are not independent submissions "
                           f"({pair_rows} pairs over {unique} submissions): "
                           f"{line.strip()[:110]}")
    if "not additive" not in md:
        bad.append("reports/f_extension.md no longer states that the axis totals are "
                   "not additive")
    return bad


def load_inputs(root: Path, splits_dir: str = "splits_v2") -> dict:
    """Resolve every layer the gate recomputes from, and report which are absent.

    `root_causes` and `hard` feed rules that only apply where the layer exists (a
    root-cause label, a cleared code snippet), so they are optional; the rest are
    required and an absence is a skip, not a failure -- the comparison is impossible
    rather than wrong, exactly as `scripts/gate_inputs.py` prescribes.
    """
    paths = {
        "corpus": root / "derived_rejections" / "rejection_corpus.jsonl",
        "negatives": root / "jsonl" / "negative_findings.jsonl",
        "findings": root / "jsonl" / "findings.jsonl",
        "hard": root / "derived" / "hard_negatives.jsonl",
        "root_causes": root / "taxonomy" / "assignments_v1.jsonl",
        "fa": root / "benchmark" / f"{FA_NAME}.jsonl",
        "fb": root / "benchmark" / f"{FB_NAME}.jsonl",
        "manifest": root / "benchmark" / "manifest.json",
        "stats": root / "reports" / "f_extension_stats.json",
        "markdown": root / "reports" / "f_extension.md",
        "splits": root / splits_dir,
    }
    optional = {"root_causes", "hard", "markdown"}
    required = [path for name, path in paths.items() if name not in optional]
    required += [paths["splits"] / f"{split}.jsonl" for split in SPLITS]
    missing = absent(root, required)
    if missing:
        return {"missing": missing, "total": len(required), "paths": paths}
    return {"missing": [], "total": len(required), "paths": paths}


def check(root: Path, splits_dir: str = "splits_v2") -> tuple[int, list[str], dict]:
    inputs = load_inputs(root, splits_dir)
    if inputs["missing"]:
        return SKIP_RC, [], inputs
    paths = inputs["paths"]
    corpus = _rows(paths["corpus"])
    if not corpus:
        return SKIP_RC, [], inputs
    negatives = _rows(paths["negatives"])
    findings = _rows(paths["findings"])
    hard = _rows(paths["hard"]) if paths["hard"].exists() else []
    root_causes = _rows(paths["root_causes"]) if paths["root_causes"].exists() else []
    fa = _rows(paths["fa"])
    fb = _rows(paths["fb"])
    stats = _json(paths["stats"])
    manifest = _json(paths["manifest"])
    md = paths["markdown"].read_text(encoding="utf-8") if paths["markdown"].exists() else ""
    published = published_splits(paths["splits"])

    corpus_by_id: dict[str, dict] = {}
    for record in corpus:
        fid = record.get("finding_id")
        if fid in corpus_by_id:
            continue
        corpus_by_id[fid] = record
    ids = [record.get("finding_id") for record in corpus]
    negatives_by_id = {(row.get("finding") or {}).get("id"): row for row in negatives}
    findings_by_id = {(row.get("finding") or {}).get("id"): row for row in findings}
    hard_by_id = {row.get("source_record", {}).get("id"): row for row in hard}
    root_cause = {row["record_id"]: row["primary"] for row in root_causes
                  if not row.get("unlabelled") and row.get("primary") not in (None, "RC-99")}

    bad: list[str] = []
    if len(set(ids)) != len(ids):
        bad.append(f"corpus holds {len(ids)} rows with {len(set(ids))} unique finding ids")
    if sorted(AXES) != sorted(fx.AXES):
        bad.append(f"the builder's axis set {list(fx.AXES)} is not the corpus METRICS "
                   f"{list(AXES)}")
    bad += check_fa_row_set(fa, corpus_by_id, negatives_by_id)
    bad += check_fa_keys(fa)
    bad += check_fa_axes(fa, corpus_by_id)
    bad += check_fa_not_technical(fa)
    bad += check_fa_independence(fa)
    bad += check_fa_leakage(fa, corpus_by_id)
    bad += check_fa_packet(fa, corpus_by_id, negatives_by_id, hard_by_id)
    bad += check_fb_row_set(fb, negatives_by_id, findings_by_id, corpus_by_id)
    bad += check_fb_positives(fb, negatives_by_id, findings_by_id)
    bad += check_fb_negatives(fb, negatives_by_id, findings_by_id, root_cause)
    bad += check_fb_ambiguous(fb)
    bad += check_fb_leakage(fb, negatives_by_id)
    bad += check_splits(fa, fb, corpus_by_id, published)
    bad += check_split_stats(stats, corpus, corpus_by_id, findings_by_id, published)
    bad += check_fa_counts(fa, stats, manifest, corpus, corpus_by_id, negatives_by_id)
    bad += check_fb_counts(fb, stats, manifest, negatives_by_id, findings_by_id)
    bad += check_fb_exclusion_rule(fb, corpus, negatives_by_id, findings_by_id)
    bad += check_prose(md, stats)
    summary = {
        "fa_rows": len(fa), "fa_labeled": sum(1 for r in fa
                                              if r.get("answer_key_status") == "labeled"),
        "fb_rows": len(fb),
        "fb_same": sum(1 for r in fb if (r.get("answer_key") or {})
                       .get("relationship") == "same_vulnerability"),
        "fb_distinct": sum(1 for r in fb if (r.get("answer_key") or {})
                           .get("relationship") == "distinct_vulnerability"),
        "fb_ambiguous": sum(1 for r in fb if (r.get("answer_key") or {})
                            .get("relationship") == "ambiguous"),
        "fb_candidates": len({(r.get("source") or {}).get("candidate_record_id")
                              for r in fb}),
        "corpus": len(corpus),
    }
    return (1 if bad else 0), bad, {**summary, "missing": []}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent),
                    help="tree to verify (defaults to this repository)")
    ap.add_argument("--splits", default="splits_v2",
                    help="split authority the extension must inherit (record ids per split)")
    ap.add_argument("--check", action="store_true",
                    help="this gate is always check-only; accepted for the gate contract")
    ap.add_argument("--quiet", action="store_true", help="print only a failure summary")
    args = ap.parse_args()
    rc, bad, summary = check(Path(args.root), args.splits)
    if rc == SKIP_RC:
        print(skip_line(tool="scripts/check_f_extension.py",
                        what="F-extension canonical or generated inputs",
                        missing=summary["missing"], total=summary["total"],
                        remedy="python scripts/build_f_extension.py on a full checkout"))
        return SKIP_RC
    if bad:
        for violation in bad[:40]:
            print(f"VIOLATION: {violation}")
        print(f"{len(bad)} F-extension violation(s)")
        return 1
    if not args.quiet:
        print(f"F-extension consistent: {summary['corpus']} corpus records, "
              f"F-A {summary['fa_rows']} rows ({summary['fa_labeled']} labeled), "
              f"F-B {summary['fb_rows']} pairs over "
              f"{summary['fb_candidates']} candidate submissions "
              f"(same {summary['fb_same']}, distinct {summary['fb_distinct']}, "
              f"ambiguous {summary['fb_ambiguous']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
