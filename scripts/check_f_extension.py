def _rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip()]


def _json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def _keys(node, prefix=""):
    """Every dict key path under `node`, for key-level leakage rules."""
    if isinstance(node, dict):
        for key, value in node.items():
            path = f"{prefix}.{key}" if prefix else str(key)
            yield path
            yield from _keys(value, path)
    elif isinstance(node, list):
        for item in node:
            yield from _keys(item, prefix)


def _strings(node):
    """Every string value under `node` (dict keys are not values)."""
    if isinstance(node, dict):
        for value in node.values():
            yield from _strings(value)
    elif isinstance(node, list):
        for value in node:
            yield from _strings(value)
    elif isinstance(node, str):
        yield node


def _stable_id(*parts: str) -> str:
    """The builder's row-id digest, recomputed here rather than trusted."""
    return hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()[:20]


def _fa_record_id(row_id: str, split: str) -> str | None:
    """The record an `FA::<split>::<record>` row claims to cover.

    The shared benchmark row contract puts the family key and the split in the id, so
    a row cannot be moved between splits without changing its identity - and a checker
    that parsed the old digest form would silently accept an id that no longer exists.
    """
    prefix = f"FA::{split}::"
    if not row_id.startswith(prefix):
        return None
    return row_id[len(prefix):] or None


def _excerpt(statement: dict) -> dict:
    """The builder's evidence-only projection, re-derived here."""
    out = {}
    for key in ("author", "role", "excerpt", "url", "excerpt_sha256", "excerpt_chars"):
        if statement.get(key) not in (None, "", []):
            out[key] = statement[key]
    return out


def _expected_citations(record: dict, hard: dict | None) -> list[dict]:
    """Re-derived `code_citations`: a body travels only for a cleared snippet sha."""
    allowed = {entry.get("snippet_sha256")
               for entry in (hard or {}).get("relevant_code") or []
               if entry.get("snippet_sha256")}
    blocks = []
    for entry in (record.get("code_context") or [])[:6]:
        snippet = entry.get("snippet") or ""
        digest = hashlib.sha256(snippet.encode("utf-8")).hexdigest() if snippet else None
        cleared = bool(allowed) and digest in allowed
        blocks.append({
            "file": entry.get("file"), "contract": entry.get("contract"),
            "function": entry.get("function"), "line_start": entry.get("line_start"),
            "line_end": entry.get("line_end"), "commit_sha": entry.get("commit_sha"),
            "code": snippet[:4000] if cleared else None, "text_withheld": not cleared,
        })
    return blocks


def _expected_structure(hard: dict | None) -> list[dict]:
    if not hard:
        return []
    out = []
    for fact in (hard.get("observed_code_facts") or [])[:6]:
        signals = fact.get("signals") or {}
        guards = [{"kind": g.get("kind"), "subject": g.get("subject"),
                   "operator": g.get("operator"), "line": g.get("line")}
                  for g in (fact.get("guards") or []) if isinstance(g, dict)]
        out.append({
            "file": fact.get("file"), "function": fact.get("function"),
            "modifiers": sorted(fact.get("modifiers") or []),
            "guards": sorted(guards, key=lambda g: (g.get("line") or 0,
                                                    g.get("subject") or "")),
            "required_roles": sorted(fact.get("required_roles") or []),
            "mutability": fact.get("mutability"),
            "external_call_present": bool(signals.get("has_external_call")),
            "delegatecall_present": bool(signals.get("has_delegatecall")),
        })
    return out


def _expected_packet(record: dict, negative: dict, hard: dict | None) -> dict:
    """The whole packet, re-derived from the corpus row and the record layers."""
    validation = negative.get("validation") or {}
    axes = record.get("axes") or {}
    original = record.get("original_verdict") or {}
    att = axes.get("attributed_reason") or {}
    exp = axes.get("exploit_attempt") or {}
    corr = axes.get("duplicate_corroboration") or {}
    pointer = validation.get("duplicate_of") or None
    pointer_context = None
    if pointer:
        methods = [m for m in (corr.get("methods") or [])
                   if m.get("method") == "explicit_duplicate_of_pointer"
                   and m.get("corroborating_finding") == pointer]
        pointer_context = {
            "published_pointer": pointer,
            "pointer_resolves_in_this_dataset": bool(methods),
            "target_status": methods[0].get("corroborating_status") if methods else None,
            "target_url": methods[0].get("corroborating_issue_url") if methods else None,
        }
    reasoning = negative.get("security_reasoning") or {}
    impact = reasoning.get("impact")
    return {
        "audit": record.get("audit"), "repository": record.get("repository"),
        "public_statuses": sorted(original.get("all_public_statuses") or []),
        "public_label_phrases": sorted(original.get("public_labels") or []),
        "judge_decision": validation.get("judge_decision") or None,
        "sponsor_position": validation.get("sponsor_position") or None,
        "attributed_statements": [_excerpt(s) for s in (att.get("statements") or [])],
        "participant_statements": [_excerpt(s)
                                   for s in (att.get("participant_statements") or [])],
        "claim": {
            "title": (negative.get("finding") or {}).get("title"),
            "plausibility_narrative": (negative.get("negative_analysis") or {})
            .get("why_it_looked_plausible"),
            "claimed_impact": (impact or {}).get("value") if isinstance(impact, dict)
            else impact,
        },
        "claim_code_targets": [f"{e.get('file')}::{e.get('function')}"
                               for e in (negative.get("code_context") or [])
                               if e.get("file")],
        "code_citations": _expected_citations(negative, hard),
        "observed_code_structure": _expected_structure(hard),
        "duplicate_pointer": pointer_context,
        "exploit_attempt": {
            "status": exp.get("status"), "blocker": exp.get("blocker"),
            "artefact": (exp.get("experiment") or {}).get("artifact")
            if isinstance(exp.get("experiment"), dict) else None,
        },
        "source_urls": sorted((negative.get("provenance") or {})
                              .get("source_urls") or [])[:4],
    }


def _assessable(packet: dict) -> tuple[dict[str, bool], dict[str, list[str]]]:
    """Which axes the packet can carry, re-derived from the same requirement set."""
    assessable: dict[str, bool] = {}
    missing: dict[str, list[str]] = {}
    for axis, required in fx.AXIS_REQUIREMENTS.items():
        absent_fields = [name for name in required
                         if packet.get(name) in (None, [], "", {})]
        if axis == "exploit_attempted_and_claimed_violation_not_demonstrated":
            absent_fields = [] if isinstance(packet.get("exploit_attempt"), dict) \
                else ["exploit_attempt"]
        if axis == "rejection_status_publicly_reported":
            absent_fields = [] if packet["public_statuses"] or packet["public_label_phrases"] \
                else ["public_statuses"]
        if axis == "reason_attributed_to_judge_or_sponsor":
            # No completeness signal exists for the public comment thread, so an
            # empty statement list cannot establish "no attribution exists".
            absent_fields = ([] if packet["attributed_statements"]
                             else ["attributed_statement_or_thread_completeness_record"])
        if axis == "claim_corroborated_as_duplicate_of_confirmed_finding":
            # Absence of a pointer is evidence only where the source was expected
            # to carry one; a duplicate-labelled record with no pointer is not.
            if packet["duplicate_pointer"] is None:
                duplicate_labelled = (
                    "duplicate" in packet["public_statuses"]
                    or any("duplicate" in phrase.lower()
                           for phrase in packet["public_label_phrases"]))
                if not packet["public_statuses"] and not packet["public_label_phrases"]:
                    absent_fields = ["duplicate_pointer_or_public_status_record"]
                elif duplicate_labelled:
                    absent_fields = ["duplicate_pointer_for_duplicate_labelled_record"]
                else:
                    absent_fields = []
        assessable[axis] = not absent_fields
        if absent_fields:
            missing[axis] = absent_fields
    if packet["code_citations"] and not any(c["code"] for c in packet["code_citations"]) \
            and not packet["observed_code_structure"]:
        assessable["reason_supported_by_cited_code"] = False
        missing["reason_supported_by_cited_code"] = ["cleared_code_text_or_structure"]
    return assessable, missing


def _expected_gold(record: dict) -> dict:
    metrics = record.get("metrics") or {}
    axes = record.get("axes") or {}
    gold = {axis: ("supported" if metrics.get(axis) is True
                   else "not_supported" if metrics.get(axis) is False else "unknown")
            for axis in AXES}
    axis_of_block = {
        "reason_attributed_to_judge_or_sponsor": "attributed_reason",
        "reason_supported_by_cited_code": "code_supported_reason",
        "exploit_attempted_and_claimed_violation_not_demonstrated": "exploit_attempt",
    }
    technical = [axis for axis in TECHNICAL_AXES
                 if ((axes.get(axis_of_block[axis]) or {})
                     .get("is_technical_explanation")) and gold[axis] == "supported"]
    return {"axes": gold, "technical_explanation_axes": technical,
            "counts_as_technical_reason_for_falsity": bool(
                (record.get("technical_verification") or {}).get(
                    "counts_as_technical_reason_for_why_the_claim_is_false")),
            "primary_reason_class": record.get("primary_reason_class"),
            "is_false_positive": record.get("is_false_positive")}


def _targets(record: dict) -> set[str]:
    return {f"{e.get('file')}::{e.get('function') or ''}"
            for e in (record.get("code_context") or []) if e.get("file")}


def _claim_fields(side: dict) -> list[str]:
    return [side[field] for field in SIDE_PROSE_FIELDS
            if isinstance(side.get(field), str)]


