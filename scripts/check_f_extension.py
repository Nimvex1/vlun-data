def check_fb_row_set(fb: list[dict], negatives_by_id: dict, findings_by_id: dict,
                     corpus_by_id: dict) -> list[str]:
    bad = []
    ids = [row.get("id") for row in fb]
    if len(set(ids)) != len(ids):
        bad.append(f"F-B has duplicate row ids: "
                   f"{sorted({i for i, n in Counter(ids).items() if n > 1})[:5]}")
    for row in fb:
        src = row.get("source") or {}
        cid, tid = src.get("candidate_record_id"), src.get("comparison_record_id")
        if row.get("task") != FB_NAME:
            bad.append(f"F-B row {row.get('id')}: task {row.get('task')!r}")
        if not cid or cid not in negatives_by_id:
            bad.append(f"F-B row {row.get('id')}: candidate {cid!r} is not a "
                       "negative_findings record")
        elif cid not in corpus_by_id:
            bad.append(f"F-B row {row.get('id')}: candidate {cid} is in no corpus record")
        if tid != "unresolved" and tid not in findings_by_id:
            bad.append(f"F-B row {row.get('id')}: comparison {tid!r} is not a finding id")
        if cid and tid and tid != "unresolved" and cid == tid:
            bad.append(f"F-B row {row.get('id')}: candidate compared with itself")
