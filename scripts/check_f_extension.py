def check_fa_row_set(fa: list[dict], corpus_by_id: dict, negatives_by_id: dict) -> list[str]:
    bad: list[str] = []
    ids = [row.get("id") for row in fa]
    if len(set(ids)) != len(ids):
        dupes = sorted({i for i, n in Counter(ids).items() if n > 1})
        bad.append(f"F-A has duplicate row ids: {dupes[:5]}")
    mapped: list[str] = []
    for row in fa:
        fid = _fa_record_id(str(row.get("id")), str(row.get("split")))
        if fid is None:
            bad.append(f"F-A row id {row.get('id')!r} is not FA::<split>::<record>")
            continue
        mapped.append(fid)
        if fid not in corpus_by_id:
            bad.append(f"F-A row {row.get('id')} maps to no corpus record")
        if str((row.get("source") or {}).get("record_id")) != fid:
            bad.append(f"F-A row {row.get('id')}: source.record_id "
                       f"{(row.get('source') or {}).get('record_id')!r} disagrees with the id")
        if fid not in negatives_by_id:
            bad.append(f"F-A row {row.get('id')} has no jsonl/negative_findings.jsonl record")
    mapped_set = set(mapped)
    if len(mapped_set) != len(mapped):
        bad.append(f"F-A maps {len(mapped)} rows onto {len(mapped_set)} records")
    expected = {fid for fid in corpus_by_id if fid in negatives_by_id}
    missing = sorted(expected - mapped_set)
    extra = sorted(mapped_set - expected)
    if missing:
        bad.append(f"{len(missing)} corpus records with a negative record have no F-A row, "
                   f"e.g. {missing[:3]}")
    if extra:
        bad.append(f"{len(extra)} F-A rows match no corpus/negative pair, e.g. {extra[:3]}")
    return bad


def check_fa_keys(fa: list[dict]) -> list[str]:
    bad = []
    for row in fa:
        if row.get("task") != FA_NAME:
            bad.append(f"F-A row {row.get('id')}: task {row.get('task')!r}")
        if sorted(row.get("input", {}).get("axes_to_answer") or []) != sorted(AXES):
            bad.append(f"F-A row {row.get('id')}: input.axes_to_answer is not the six "
                       "corpus metrics")
        if sorted(row.get("answer_key", {}).get("axes") or {}) != sorted(AXES):
            bad.append(f"F-A row {row.get('id')}: answer_key.axes is not the six "
                       "corpus metrics")
        if sorted(row.get("input", {}).get("answer_vocab") or []) != sorted(fx.ANSWERS):
            bad.append(f"F-A row {row.get('id')}: answer_vocab drifted from "
                       f"{list(fx.ANSWERS)}")
    return bad


def check_fa_axes(fa: list[dict], corpus_by_id: dict) -> list[str]:
    bad = []
    for row in fa:
        fid = str((row.get("source") or {}).get("record_id"))
        record = corpus_by_id.get(fid)
        if record is None:
            continue
        key = row.get("answer_key") or {}
        gold = _expected_gold(record)
        assessed = set(row.get("assessed_axes") or [])
        withheld = set(key.get("withheld_gold_axes") or [])
        for axis in AXES:
            if axis in assessed:
                expected_gold = gold["axes"][axis]
            else:
                # An unassessable axis is missing evidence, not a proven negative:
                # its gold is `unknown` and the axis is named in withheld_gold_axes.
                expected_gold = "unknown"
                if axis not in withheld:
                    bad.append(f"{fid}: axis {axis} is unassessable but is not named in "
                               "withheld_gold_axes")
            if key.get("axes", {}).get(axis) != expected_gold:
                bad.append(f"{fid}: axis {axis} gold {key.get('axes', {}).get(axis)!r} "
                           f"but the reassessed gold is {expected_gold!r} "
                           f"(corpus metrics[{axis}]="
                           f"{(record.get('metrics') or {}).get(axis)!r})")
        expected_technical = sorted(
            axis for axis in gold["technical_explanation_axes"]
            if key.get("axes", {}).get(axis) == "supported")
        if sorted(key.get("technical_explanation_axes") or []) != expected_technical:
            bad.append(f"{fid}: technical_explanation_axes "
                       f"{sorted(key.get('technical_explanation_axes') or [])} but the "
                       f"corpus gives {expected_technical}")
        if bool(key.get("counts_as_technical_reason_for_falsity")) != bool(
                gold["counts_as_technical_reason_for_falsity"]):
            bad.append(f"{fid}: counts_as_technical_reason_for_falsity "
                       f"{key.get('counts_as_technical_reason_for_falsity')!r} but corpus "
                       "technical_verification gives "
                       f"{gold['counts_as_technical_reason_for_falsity']!r}")
        if key.get("primary_reason_class") != record.get("primary_reason_class"):
            bad.append(f"{fid}: primary_reason_class changed on the way to the key")
    return bad


def check_fa_not_technical(fa: list[dict]) -> list[str]:
    bad = []
    for row in fa:
        rid = row.get("id")
        key = row.get("answer_key") or {}
        tech = key.get("technical_explanation_axes") or []
        for axis in NON_TECHNICAL_AXES:
            if axis in tech:
                bad.append(f"{rid}: {axis} is listed as a technical explanation of falsity; "
                           "a duplicate corroboration and a public status label are not one")
        for axis in tech:
            if axis not in TECHNICAL_AXES:
                bad.append(f"{rid}: technical axis {axis!r} is outside the technical set "
                           f"{list(TECHNICAL_AXES)}")
            if key.get("axes", {}).get(axis) != "supported":
                bad.append(f"{rid}: technical axis {axis} is not answered supported")
        if tech and not key.get("counts_as_technical_reason_for_falsity"):
            bad.append(f"{rid}: lists technical axes {tech} but the falsity flag is false")
        if not tech and key.get("counts_as_technical_reason_for_falsity"):
            bad.append(f"{rid}: falsity flag is true with no technical axis")
    return bad


def check_fa_independence(fa: list[dict]) -> list[str]:
    """Axes are overlapping, so a multi-axis row must exist and must not be forced."""
    bad = []
    multi = sum(1 for row in fa
                if sum(1 for v in (row.get("answer_key", {}).get("axes") or {}).values()
                       if v == "supported") > 1)
    if not multi:
        bad.append("no F-A row supports more than one axis: the six axes would be a "
                   "partition, which they are not")
    for row in fa:
        axes = row.get("answer_key", {}).get("axes") or {}
        if axes.get("unknown_or_insufficient_evidence") == "supported" and any(
                axes.get(other) == "supported"
                for other in ("reason_attributed_to_judge_or_sponsor",
                              "reason_supported_by_cited_code",
                              "exploit_attempted_and_claimed_violation_not_demonstrated")):
            bad.append(f"{row.get('id')}: unknown_or_insufficient_evidence is supported "
                       "alongside a positive evidence axis")
    return bad


def check_fa_leakage(fa: list[dict], corpus_by_id: dict) -> list[str]:
    bad = []
    axis_names = set(AXES)
    for row in fa:
        fid = str((row.get("source") or {}).get("record_id"))
        record = corpus_by_id.get(fid)
        inp = row.get("input") or {}
        packet = inp.get("evidence_packet") or {}
        key = row.get("answer_key") or {}
        for path in _keys(packet):
            leaf = path.rsplit(".", 1)[-1]
            hits = [term for term in JUDGEMENT_KEYS if term in leaf]
            if hits:
                bad.append(f"{fid}: packet key {path} carries the derived-conclusion "
                           f"field(s) {hits}")
        for text in _strings(packet):
            if text in axis_names:
                continue
            for term in JUDGEMENT_KEYS:
                if term in PROSE_SAFE_TERMS:
                    continue
                if term in text:
                    bad.append(f"{fid}: packet text carries the derived conclusion "
                               f"{term!r}: {text[:90]!r}")
        if record is not None:
            for value in _strings(packet):
                if value == record.get("primary_reason_class"):
                    bad.append(f"{fid}: packet carries the conclusion "
                               f"primary_reason_class={value!r} verbatim")
        for akey in key:
            if akey in ("assessed_axes", "axes", "technical_explanation_axes",
                        "counts_as_technical_reason_for_falsity", "primary_reason_class",
                        "is_false_positive") and _has_key(inp, akey):
                bad.append(f"{fid}: input mirrors answer-key field {akey!r}")
    return bad


def _has_key(node, name: str) -> bool:
    if isinstance(node, dict):
        for k, value in node.items():
            if str(k) == name or _has_key(value, name):
                return True
    elif isinstance(node, list):
        return any(_has_key(value, name) for value in node)
    return False


def check_fa_packet(fa: list[dict], corpus_by_id: dict, negatives_by_id: dict,
                    hard_by_id: dict) -> list[str]:
    """Full re-derivation of every packet field, the assessability rule and the status."""
    bad = []
    for row in fa:
        fid = str((row.get("source") or {}).get("record_id"))
        record, negative = corpus_by_id.get(fid), negatives_by_id.get(fid)
        if record is None or negative is None:
            continue
        expected = _expected_packet(record, negative, hard_by_id.get(fid))
        packet = (row.get("input") or {}).get("evidence_packet") or {}
        for field, value in expected.items():
            if packet.get(field) != value:
                bad.append(f"{fid}: packet field {field} differs from the canonical "
                           "re-derivation")
        for field in packet:
            if field not in expected:
                bad.append(f"{fid}: packet carries field {field!r} that the canonical "
                           "layers do not produce")
        assessable, missing = _assessable(packet)
        assessed = [axis for axis in AXES if assessable[axis]]
        if row.get("assessed_axes") != assessed:
            bad.append(f"{fid}: assessed_axes {row.get('assessed_axes')} but the packet "
                       f"can carry {assessed}")
        if (row.get("answer_key") or {}).get("assessed_axes") != assessed:
            bad.append(f"{fid}: answer_key.assessed_axes disagrees with the packet")
        unassessed = {axis: missing.get(axis, []) for axis in AXES
                      if not assessable[axis]}
        if row.get("unassessed_axes") != unassessed:
            bad.append(f"{fid}: unassessed_axes {row.get('unassessed_axes')} but the "
                       f"missing evidence is {unassessed}")
        status = ("labeled" if not unassessed
                  else "unlabeled" if len(unassessed) == len(AXES) else "partial")
        if row.get("answer_key_status") != status:
            bad.append(f"{fid}: answer_key_status {row.get('answer_key_status')!r} but "
                       f"the packet makes it {status!r}")
        if status == "labeled" and row.get("unlabelled_reason") is not None:
            bad.append(f"{fid}: labeled row still carries unlabelled_reason")
        if status != "labeled" and not row.get("unlabelled_reason"):
            bad.append(f"{fid}: {status} row names no unlabelled_reason")
    return bad


