#!/usr/bin/env python3
"""Gate: the F-extension must say one thing in its rows, its keys and its reports.

`benchmark/Fa_rejection_evidence_axis_vector.jsonl` and
`benchmark/Fb_duplicate_radar_pair.jsonl` are generated by
`scripts/build_f_extension.py` from the canonical rejection corpus
(`derived_rejections/rejection_corpus.jsonl`) plus the `jsonl/` record layer. This
script re-derives everything from those canonical layers -- it never reads the
builder's own summary as an authority -- and fails with a precise message when a
committed row, answer key, manifest entry or report line is not supported by them.

The invariants, in the order they are checked:

  1. row set      one F-A row per corpus record that has a negative record, no
                   duplicates, no orphans;
  2. axis truth   the six axis names are `build_rejection_corpus.METRICS`, the gold
                   vector is that record's `metrics` booleans re-expressed, and the
                   axes stay independent (never a partition);
  3. duplicate-is-not-technical  a duplicate corroboration and a public status label
                   may never be listed as a technical explanation of falsity, and the
                   technical flag is the corpus field;
  4. F-A leakage  the model-facing packet carries evidence, not the derived
                   conclusions: no judgement vocabulary, no answer-key mirror;
  5. F-B positives   every `same_vulnerability` pair is an explicit
                   `validation.duplicate_of` pointer that resolves in `jsonl/findings.jsonl`;
  6. F-B negatives   every `distinct_vulnerability` pair carries distinctness
                   evidence, is not the candidate's own pointer target, has disjoint
                   cited file::function sets, and differing root-cause labels where
                   both sides have one;
  7. F-B ambiguous  ambiguous is never counted as distinct, and an unresolved
                   comparison makes the row `unlabeled`, never `labeled`;
  8. F-B leakage  no pointer string, comparison id, published status word or triage
                   judgement phrase reaches the model-facing pair;
  9. split        the published split layer (`splits_v2/`) is re-read and inherited:
                   every row matches it, no submission, canonical finding, pair or
                   audit cluster straddles train/validation/test, and all three
                   splits are non-empty;
 10. counts       `benchmark/manifest.json` and `reports/f_extension_stats.json`
                   equal the recount of the rows;
 11. non-inflation  pairs are reported over the submissions that back them, and no
                   prose calls the pair count a number of independent submissions.

The packet is recomputed field by field from the canonical layers, which is what
makes the leakage rules checkable: a derived conclusion smuggled into the packet
appears as a field the recomputation does not produce.

    python scripts/check_f_extension.py                  # report, exit 1 on violation
    python scripts/check_f_extension.py --check --quiet   # same, no banner
    python scripts/check_f_extension.py --root <tree>     # verify a copy

stdlib only; writes nothing.

"""

