#!/usr/bin/env python3
"""Generate reports/reproducibility_report.md from the live gate reports.

The README links this file as "the live PASS/FAIL matrix". It used to be a
hand-written point-in-time audit record from 2026-10-07 that still quoted
119 manifest checks, 16 reproducibility checks and 44 tests while the gates
ran 171/19/118 — and nothing caught the drift, because prose is not gated.

This generator composes the report from the JSON each gate already writes,
so the numbers cannot go stale. Gates that write a report:

    reports/validation_report.json              scripts/validate.py
    reports/v3/validation_v3.json               scripts/validate_v3.py
    reports/v3/validation_v31.json              scripts/validate_v31.py
    reports/manifest_checks.json                scripts/check_manifests.py
    reports/reproducibility_checks_summary.json scripts/check_reproducibility.py
    Vbeta/reports_vbeta/validation_vbeta.json   Vbeta/scripts/validate_vbeta.py

The reproducibility gate's counts come from its COMMITTED summary, not the
git-ignored per-check snapshot: a fresh clone must be able to regenerate
this report byte-identically (regression 2026-10-25: the snapshot's absence
rendered the row as SKIPPED and failed the doc test on every clean
checkout).

A gate report that is missing is rendered as SKIPPED, never as a pass.

    python scripts/build_repro_report.py
    python scripts/build_repro_report.py --check
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "reports" / "reproducibility_report.md"

SOURCES = [
    ("v1 authorship gate", "scripts/validate.py",
     "reports/validation_report.json", "checks"),
    ("v3 gate", "scripts/validate_v3.py",
     "reports/v3/validation_v3.json", "total"),
    ("v3.1 gate", "scripts/validate_v31.py",
     "reports/v3/validation_v31.json", "total"),
    ("Vbeta gate", "Vbeta/scripts/validate_vbeta.py",
     "Vbeta/reports_vbeta/validation_vbeta.json", None),
    ("cross-manifest", "scripts/check_manifests.py",
     "reports/manifest_checks.json", "checks_total"),
    ("reproducibility", "scripts/check_reproducibility.py",
     "reports/reproducibility_checks_summary.json", "checks_total"),
]


def load(rel: str):
    try:
        return json.loads((ROOT / rel).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def vbeta_total(doc) -> int:
    return len((doc or {}).get("checks", []))


def render() -> str:
    """Deterministic by construction.

    Only environment-INDEPENDENT facts are rendered: how many checks each
    gate runs and how many failed. The per-check PASS/SKIP split is NOT
    rendered, because it legitimately differs by machine: a checkout with
    the git-ignored `V3/clones` and `work/` present runs the derived/
    rebuild-parity gate, and a fresh CI clone skips it. A report that
    embedded those statuses could never be current on both, and gating it
    with --check made CI fail on a run that was actually green.

    The per-check matrix is still published: check_reproducibility.py
    writes reports/reproducibility_checks.json on every run, and the CI run
    is the live matrix. That file is git-ignored precisely because it is a
    machine-local snapshot.
    """
    rows = []
    for label, script, rel, key in SOURCES:
        doc = load(rel)
        if doc is None:
            rows.append((label, script, "SKIPPED", "-"))
            continue
        if label == "Vbeta gate":
            checks = (doc or {}).get("checks", [])
            total = len(checks)
            crit = (doc or {}).get("critical_failures")
            got = f"{total} checks" if total else "SKIPPED"
            rows.append((label, script, got,
                         crit if crit is not None else "-"))
        elif key == "checks":
            rows.append((label, script, f"{doc.get(key, 0)} checks",
                         doc.get("critical_failures", 0)))
        else:
            rows.append((label, script, f"{doc.get(key, 0)} checks",
                         doc.get("checks_failed_critical", 0)))

    L = ["# Reproducibility / validation report (live)", "",
         "GENERATED by `scripts/build_repro_report.py` from the JSON each gate",
         "writes. Do not hand-edit: prose counts are exactly the class of",
         "claim that rots silently.", "",
         "## Gate status", "",
         "Each gate writes its own JSON report; this table is composed from",
         "those files, never typed by hand. It shows the size of each gate and",
         "its critical failures -- the two numbers that do not depend on the",
         "machine.", "",
         "| Gate | Script | Checks | Critical failures |",
         "|---|---|---|---|"]
    for label, script, got, crit in rows:
        L.append(f"| {label} | `{script}` | {got} | {crit} |")

    L += ["", "## Where the per-check matrix lives", "",
          "The per-check PASS/SKIP statuses are deliberately NOT in this file.",
          "They are machine-dependent: a checkout with the git-ignored",
          "`V3/clones` and `work/` present executes the `derived/` rebuild",
          "gate, while a fresh CI clone skips it. Pinning those statuses in a",
          "committed file makes it current on one machine and stale on every",
          "other one.", "",
          "- This run: `python scripts/check_reproducibility.py` prints the full",
          "  matrix and writes `reports/reproducibility_checks.json`",
          "  (git-ignored: a machine-local snapshot, not a published fact).",
          "  Its machine-independent counts (gate size, critical failures)",
          "  are committed as",
          "  `reports/reproducibility_checks_summary.json`, which is what the",
          "  table above quotes.",
          "- The authoritative live matrix is the CI run for the commit, plus",
          "  `python scripts/run_gates.py` locally.", "",
          "## Skips are honest", "",
          "A skip is `skipped_no_network`: the check needs `V3/clones` or",
          "`work/`, which are git-ignored and never redistributed. A skip is",
          "never rendered as a pass anywhere in this repository.", "",
          "## What is NOT claimed", "",
          "- A green matrix does not mean the dataset is correct, only that",
          "  the committed artefacts agree with each other and with the",
          "  pipeline that produced them.",
          "- Fresh clones reproduce the JSONL and derived layers. Execution",
          "  artefacts live git-ignored under `work/`; their verdicts stay",
          "  checkable through committed `result.json` files, whose recorded",
          "  sha256 values are verified by `tests/test_artefact_hashes.py`.",
          ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    want = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != want:
            print("STALE reports/reproducibility_report.md -- run: "
                  "python scripts/build_repro_report.py")
            return 1
        print("reproducibility_report.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(want.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())