#!/usr/bin/env python3
"""The Vbeta build gate. Fails on critical integrity problems in Vbeta/.

    python Vbeta/scripts/validate_vbeta.py
    python Vbeta/scripts/validate_vbeta.py --quiet

Checks (read-only, except the validation report itself, which lives in Vbeta/)::

  structure     JSON/JSONL validity, required fields, id uniqueness
  provenance    every candidate cites a registered source + live receipt
  consistency   closed vocabularies, L1-requires-PoC, nothing above L1
  references    records/splits/benchmark resolve to ledger rows; benchmark
                answers rebuildable from records
  counts        manifest numbers recomputed from the files
  versions      every Vbeta artefact agrees on vbeta-1.0
  isolation     PRESENT sentinels match present_snapshot.json (warn-only:
                the user may evolve PRESENT deliberately)

Writes Vbeta/reports_vbeta/validation_vbeta.json.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vlun_vbeta as V  # noqa: E402

U = V.UNKNOWN


class Report:
    def __init__(self, quiet: bool = False):
        self.checks: list[dict] = []
        self.quiet = quiet

    def add(self, group: str, check: str, ok: bool, failures=None,
            detail=None, critical=True):
        fails = list(failures or []) if not ok else []
        self.checks.append({"group": group, "check": check, "ok": bool(ok),
                            "critical": critical,
                            "failure_count": len(fails),
                            "failures": fails[:25], "detail": detail})
        if not self.quiet:
            mark = "ok  " if ok else ("FAIL" if critical else "warn")
            extra = f"  ({len(fails)} failures)" if fails else ""
            V.log(f"  [{mark}] {group}/{check}{extra}")
            for f in fails[:5]:
                V.log(f"         - {f}")
        return ok


def _load_jsonl(path: Path, rep: Report, group: str) -> list[dict]:
    rows: list[dict] = []
    bad: list[str] = []
    try:
        with open(path, encoding="utf-8") as fh:
            for i, line in enumerate(fh, 1):
                line = line.strip()
                if not line:
                    continue
                try:
                    rows.append(json_loads(line))
                except Exception as exc:  # noqa: BLE001
                    bad.append(f"{path.name}:{i}: {exc}")
    except OSError as exc:
        bad.append(f"{path}: {exc}")
    rep.add(group, f"{path.parent.name}/{path.name}_valid_jsonl", not bad, bad)
    return rows


def json_loads(text: str):
    import json
    return json.loads(text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--resnapshot", default=None, metavar="REASON",
                    help="refresh present_snapshot.json sentinels (use ONLY "
                         "when PRESENT changed via its authorized writer, "
                         "e.g. README regenerated by generate_readme.py; "
                         "the reason is recorded in the snapshot)")
    args = ap.parse_args()
    if args.resnapshot:
        from build_vbeta import SENTINELS
        snap = {"resnapshot_reason": args.resnapshot,
                "sentinel_sha256": {
                    s: V.text_file_sha256(V.ROOT / s)
                    for s in SENTINELS},
                "note": "baseline: PRESENT must stay at this text "
                        "(line-ending-independent hash); "
                        "validate_vbeta.py warns on drift"}
        V.write_json(V.VBETA_DIR / "present_snapshot.json", snap)
        V.log(f"resnapshotted: {args.resnapshot}")
        return 0
    rep = Report(args.quiet)
    V.log("validate_vbeta.py")

    ledger = _load_jsonl(V.DERIVED_VB / "candidate_ledger.jsonl", rep, "structure")
    records = _load_jsonl(V.DERIVED_VB / "records.jsonl", rep, "structure")
    negatives = _load_jsonl(V.DERIVED_VB / "negatives.jsonl", rep, "structure")
    findings = _load_jsonl(V.JSONL_VB / "findings.jsonl", rep, "structure")
    src_rows = _load_jsonl(V.JSONL_VB / "sources.jsonl", rep, "structure")
    receipts = _load_jsonl(V.FETCHED / "receipts.jsonl", rep, "structure")

    # ---- structure ------------------------------------------------------
    for name, rows, required in [
        ("ledger", ledger, ["candidate_id", "source_id", "finding_title",
                            "language", "ecosystem", "verification_level",
                            "decision", "quality_score", "source_location",
                            "dataset_version"]),
        ("records", records, ["finding_id", "source_id", "title", "language",
                              "ecosystem", "verification_level", "decision",
                              "dataset_version"]),
    ]:
        missing = [f"{name}[{i}]: lacks {k}" for i, r in enumerate(rows)
                   for k in required if k not in r]
        rep.add("structure", f"{name}_required_fields", not missing, missing)

    for name, rows, key in [("ledger", ledger, "candidate_id"),
                            ("records", records, "finding_id")]:
        seen: set[str] = set()
        dupes = []
        for r in rows:
            k = r.get(key)
            if k in seen:
                dupes.append(str(k))
            seen.add(k)
        rep.add("structure", f"{name}_unique_ids", not dupes, dupes)

    # ---- provenance ------------------------------------------------------
    try:
        reg = {s["source_id"] for s in V.load_sources()}
    except Exception as exc:  # noqa: BLE001
        reg = set()
        rep.add("provenance", "sources_json_readable", False, [str(exc)])
    else:
        rep.add("provenance", "sources_json_readable", True)
    rec_sources = {r.get("source_id") for r in receipts}
    bad_cites = [r.get("candidate_id") for r in ledger
                 if r.get("source_id") not in reg
                 or r.get("source_id") not in rec_sources]
    rep.add("provenance", "every_candidate_cites_registered_receipt",
            not bad_cites, bad_cites)
    bad_urls = [r.get("candidate_id") for r in ledger
                if r.get("origin", "harvested") != "user_contributed"
                and not (r.get("source_location") or "").startswith("https://")]
    rep.add("provenance", "source_locations_are_https", not bad_urls, bad_urls)
    authored = [r for r in ledger
                if r.get("origin", "harvested") == "user_contributed"]
    bad_auth = [r.get("candidate_id") for r in authored
                if r.get("decision") != "IMPORT_AS_UNVERIFIED"
                or r.get("verification_level") != "L0"]
    rep.add("provenance", "operator_rows_stay_unverified_L0",
            not bad_auth, bad_auth,
            detail="user_contributed rows: IMPORT_AS_UNVERIFIED + L0 only")

    # ---- consistency ------------------------------------------------------
    bad_dec = [r.get("candidate_id") for r in ledger
               if r.get("decision") not in V.DECISIONS]
    rep.add("consistency", "decisions_closed_vocab", not bad_dec, bad_dec)
    bad_lvl = [r.get("candidate_id") for r in ledger
               if r.get("verification_level") not in V.VERIFICATION_LEVELS]
    rep.add("consistency", "levels_closed_vocab", not bad_lvl, bad_lvl)
    cands = {c["cid"]: c for c in
             V.read_json(V.VBETA_DIR / "candidates.json")}
    for extra in ("solodit_candidates.json", "web3bugs_candidates.json",
                    "scabench_candidates.json", "lisabench_candidates.json"):
        extra_path = V.VBETA_DIR / extra
        if extra_path.exists():
            for c in V.read_json(extra_path):
                cands[c["cid"]] = c
    l1_without_poc = [r.get("candidate_id") for r in ledger
                      if r.get("verification_level") == "L1"
                      and not cands.get(r["candidate_id"], {}).get("poc_observed")]
    rep.add("consistency", "L1_requires_observed_poc", not l1_without_poc,
            l1_without_poc)
    above_l1 = [r.get("candidate_id") for r in ledger
                if r.get("verification_level") not in ("L0", "L1")]
    rep.add("consistency", "nothing_above_L1", not above_l1, above_l1)
    bad_neg = [r.get("finding_id") for r in records
               if r.get("decision") == "IMPORT_AS_NEGATIVE"
               and r.get("negative_class") not in V.NEGATIVE_CLASSES]
    rep.add("consistency", "negative_classes_closed_vocab", not bad_neg, bad_neg)

    # ---- references --------------------------------------------------------
    ledger_ids = {r.get("candidate_id") for r in ledger}
    bad_refs = [r.get("finding_id") for r in records
                if r.get("finding_id") not in ledger_ids]
    rep.add("references", "records_resolve_to_ledger", not bad_refs, bad_refs)
    neg_ids = {r.get("finding_id") for r in negatives}
    rec_neg_ids = {r.get("finding_id") for r in records
                   if r.get("decision") == "IMPORT_AS_NEGATIVE"}
    rep.add("references", "negatives_match_records",
            neg_ids == rec_neg_ids,
            [f"negatives={sorted(neg_ids)[:5]} records={sorted(rec_neg_ids)[:5]}"]
            if neg_ids != rec_neg_ids else None)

    try:
        split = V.read_json(V.SPLITS_VB / "split.json")
        split_ids = set(split["splits"]["train"]) | set(split["splits"]["validation"]) \
            | set(split["splits"]["test"])
        rec_ids = {r.get("finding_id") for r in records}
        rep.add("references", "splits_cover_records_exactly",
                split_ids == rec_ids,
                [f"split_only={sorted(split_ids - rec_ids)[:5]} "
                 f"record_only={sorted(rec_ids - split_ids)[:5]}"]
                if split_ids != rec_ids else None)
        asg = split.get("assignment", {})
        span = [i for i in rec_ids
                if asg.get(i.split(":")[0], None) is None
                and True]
        # by-source rule: every record's source has exactly one split
        src_split: dict[str, set[str]] = {}
        for i in rec_ids:
            sid = i.split(":")[0]
            for sname, ids in split["splits"].items():
                if i in ids:
                    src_split.setdefault(sid, set()).add(sname)
        spanning = [s for s, ss in src_split.items() if len(ss) != 1]
        rep.add("references", "no_source_spans_splits", not spanning, spanning)
    except Exception as exc:  # noqa: BLE001
        rep.add("references", "splits_readable", False, [str(exc)])

    try:
        bench_u = _load_jsonl(V.BENCH_VB / "vbeta_U_language_routing.jsonl", rep, "references")
        bench_v = _load_jsonl(V.BENCH_VB / "vbeta_V_source_tier_routing.jsonl", rep, "references")
        recmap = {r.get("finding_id"): r for r in records}
        bad_bu = [t.get("task_id") for t in bench_u
                  if t.get("finding_id") not in recmap
                  or t.get("answer") != recmap[t["finding_id"]]["language"]]
        rep.add("references", "U_answers_rebuild_from_records", not bad_bu, bad_bu)
        bad_bv = [t.get("task_id") for t in bench_v
                  if t.get("finding_id") not in recmap
                  or t.get("answer") != str(recmap[t["finding_id"]]["source_tier"])]
        rep.add("references", "V_answers_rebuild_from_records", not bad_bv, bad_bv)
    except Exception as exc:  # noqa: BLE001
        rep.add("references", "benchmark_readable", False, [str(exc)])

    # ---- evidence (enriched rows only; absent elsewhere) -------------------
    CONF = {"high", "medium", "low", "unknown"}
    bad_conf = [r.get("finding_id") for r in records
                if r.get("evidence") is not None
                and r["evidence"].get("taxonomy_confidence") not in CONF]
    rep.add("evidence", "confidence_closed_vocab", not bad_conf, bad_conf)
    bad_vp = [r.get("finding_id") for r in records
              if r.get("evidence") is not None
              and r["evidence"].get("verified_patch") not in (False, None)]
    rep.add("evidence", "no_verified_patch_without_artefacts", not bad_vp,
            bad_vp,
            detail="verified_patch=true would require run artefacts (none exist)")
    bad_tax = [r.get("finding_id") for r in records
               if r.get("evidence") is not None
               and not (r["evidence"].get("taxonomy") or "").strip()]
    rep.add("evidence", "taxonomy_present_when_evidence", not bad_tax, bad_tax)
    bad_proof = [r.get("finding_id") for r in records
                 if r.get("evidence") is not None
                 and r["evidence"].get("proof_type")
                 not in ("published_poc_in_report", "none_observed")]
    rep.add("evidence", "proof_type_closed_vocab", not bad_proof, bad_proof)
    bad_sevnorm = [r.get("finding_id") for r in records
                   if r.get("severity_normalized")
                   not in ("critical", "high", "medium", "low",
                           "informational", "unknown")]
    rep.add("evidence", "severity_normalized_closed_vocab", not bad_sevnorm,
            bad_sevnorm,
            detail="derived field only; severity_observed kept verbatim")

    # ---- counts --------------------------------------------------------------
    try:
        manifest = V.read_json(V.DERIVED_VB / "manifest.json")
        import collections
        checks = {
            "candidate_count": len(ledger),
            "record_count": len(records),
            "source_count": len(reg),
        }
        mism = [f"{k}: manifest={manifest.get(k)} computed={v}"
                for k, v in checks.items() if manifest.get(k) != v]
        dec = dict(collections.Counter(r.get("decision") for r in ledger))
        if manifest.get("decisions") != dec:
            mism.append(f"decisions: manifest={manifest.get('decisions')} computed={dec}")
        rep.add("counts", "manifest_matches_files", not mism, mism)
    except Exception as exc:  # noqa: BLE001
        rep.add("counts", "manifest_readable", False, [str(exc)])

    # ---- versions ---------------------------------------------------------------
    version_files = [V.DERIVED_VB / "manifest.json",
                     V.BENCH_VB / "vbeta_manifest.json"]
    bad_ver: list[str] = []
    for path in version_files:
        try:
            if V.read_json(path).get("dataset_version") != V.DATASET_VERSION_VB:
                bad_ver.append(str(path))
        except Exception as exc:  # noqa: BLE001
            bad_ver.append(f"{path}: {exc}")
    for r in ledger + records:
        if r.get("dataset_version") != V.DATASET_VERSION_VB:
            bad_ver.append(str(r.get("candidate_id") or r.get("finding_id")))
            break
    rep.add("versions", "all_vbeta_1_0", not bad_ver, bad_ver)

    # ---- isolation (warn-only) --------------------------------------------
    try:
        snap = V.read_json(V.VBETA_DIR / "present_snapshot.json")
        drift = []
        for rel, old in snap.get("sentinel_sha256", {}).items():
            p = V.ROOT / rel
            if not p.exists():
                drift.append(f"{rel}: missing")
                continue
            h = V.text_file_sha256(p)
            if h != old:
                drift.append(f"{rel}: drifted")
        rep.add("isolation", "present_sentinels_unchanged", not drift, drift,
                critical=False,
                detail="warn-only: PRESENT may evolve deliberately")
    except Exception as exc:  # noqa: BLE001
        rep.add("isolation", "snapshot_readable", False, [str(exc)],
                critical=False)

    out = {"dataset_version": V.DATASET_VERSION_VB,
           "generated_by": "Vbeta/scripts/validate_vbeta.py",
           "checks": rep.checks,
           "critical_failures": sum(1 for c in rep.checks
                                    if not c["ok"] and c["critical"])}
    V.assert_inside_vbeta(V.REPORTS_VB / "validation_vbeta.json")
    V.write_json(V.REPORTS_VB / "validation_vbeta.json", out)
    V.log(f"  critical_failures={out['critical_failures']}")
    return 1 if out["critical_failures"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
