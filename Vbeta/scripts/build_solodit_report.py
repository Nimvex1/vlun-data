#!/usr/bin/env python3
"""Generate Vbeta/reports_vbeta/solodit_ingestion_report.md from live data.

Every figure in the report is counted from the artefacts it describes:
the harvest stats, the candidate ledger, the admitted records and the
splits. The previous hand-written report drifted (it claimed 733 admitted
records and language totals summing to 782 against a 670-row admitted
population) and nothing caught it because no gate compared the prose to the
data. This generator plus tests/test_vbeta_docs.py closes that.

Writes exactly one file, under Vbeta/. Never reads or writes PRESENT.

    python Vbeta/scripts/build_solodit_report.py
    python Vbeta/scripts/build_solodit_report.py --check
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

VBETA = Path(__file__).resolve().parent.parent
ROOT = VBETA.parent
OUT = VBETA / "reports_vbeta" / "solodit_ingestion_report.md"
SID = "solodit-harvest"


def jl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.open(encoding="utf-8") if l.strip()]


def render() -> str:
    stats = json.loads(
        (VBETA / "reports_vbeta" / "solodit_harvest_stats.json")
        .read_text(encoding="utf-8"))
    ledger = jl(VBETA / "derived_vbeta" / "candidate_ledger.jsonl")
    records = jl(VBETA / "derived_vbeta" / "records.jsonl")
    split = json.loads((VBETA / "splits_vbeta" / "split.json")
                       .read_text(encoding="utf-8"))

    admitted_ids = {r["finding_id"] for r in records}
    sol = [c for c in ledger if c["source_id"] == SID]
    sol_ad = [c for c in sol if c["candidate_id"] in admitted_ids]
    dec = collections.Counter(c["decision"] for c in sol)
    lv = collections.Counter(c.get("verification_level") for c in sol_ad)
    lang = collections.Counter(c.get("language") for c in sol_ad)
    imported = [c for c in sol_ad if c["decision"] == "IMPORT"]

    n = lambda x: f"{x:,}"
    lang_total = sum(lang.values())
    L: list[str] = [
        "# Solodit ingestion report (source: solodit-harvest)",
        "",
        "GENERATED by `Vbeta/scripts/build_solodit_report.py` from the",
        "harvest stats, the candidate ledger, the admitted records and the",
        "splits. Every number below is counted from those files; do not hand",
        "edit (tests/test_vbeta_docs.py fails the build on drift).",
        "",
        "## Method",
        "",
        f"- {n(stats['indexed'])} HIGH+MEDIUM cards indexed from Firecrawl",
        f"  listing pages; {n(stats['files'])} detail pages scraped verbatim to",
        "  `nextdata/*.md` (untracked, referenced by path).",
        f"- Harvested by `Vbeta/scripts/harvest_solodit.py` (deterministic,",
        "  stdlib-only) into `Vbeta/solodit_candidates.json`.",
        f"- {n(stats['rejected'])} file rejected, "
        f"{n(stats['quarantined_near_dupes'])} near-duplicate candidates",
        "  quarantined as CORROBORATION_ONLY with a `duplicate_of` link.",
        "",
        "## Counting domains (these were conflated before)",
        "",
        "| Quantity | Count | What it counts |",
        "|---|---|---|",
        f"| Harvested candidates | {n(len(sol))} | rows parsed from the scrape |",
        f"| Admitted records | {n(len(sol_ad))} | candidates that passed admission |",
        f"| Quarantined | {n(dec['CORROBORATION_ONLY'])} | near-duplicates, linked not deleted |",
        f"| IMPORT | {n(dec['IMPORT'])} | severity + status + link + title all observed |",
        f"| IMPORT_AS_UNVERIFIED | {n(dec['IMPORT_AS_UNVERIFIED'])} | observed, not fully evidenced |",
        "",
        f"Language totals below are ADMITTED records and sum to "
        f"{n(lang_total)}; the earlier report's 782 summed a different",
        "population and did not match anything.",
        "",
        "## Severity provenance",
        "",
        f"- Report severity observed on **{n(stats['with_report_severity'])}** "
        f"of {n(len(sol))} rows.",
        f"- Solodit's own Impact axis observed on "
        f"**{n(stats['with_solodit_impact_axis'])}** rows, stored as",
        "  `solodit_sidebar_observed`, never as the report's severity.",
        f"- Status observed on {n(stats['with_status'])} rows (inline",
        "  `**Status:**` labels as well as `## Team Response` headings).",
        "",
        "## Observed detail",
        "",
        f"- Description excerpt: {n(stats['with_description_excerpt'])}",
        f"- Recommendation: {n(stats['with_recommendation'])}",
        f"- PoC section: {n(stats['with_poc'])}",
        f"- Levels: " + ", ".join(f"{k} {v}" for k, v in sorted(lv.items())),
        f"- Languages: " + ", ".join(f"{k} {v}"
                                     for k, v in lang.most_common())
        + f" (sum {n(lang_total)})",
        "",
        "## Splits",
        "",
        "Split assignment is by source (no source spans splits), so every",
        "admitted Solodit record lands in the split its source owns:",
        "",
        "| Split | Solodit records |",
        "|---|---|",
    ]
    for name in ("train", "validation", "test"):
        ids = set(split.get("splits", {}).get(name, []))
        L.append(f"| {name} | {n(len(ids & admitted_ids))} |")

    L += [
        "",
        "## Honest limitations",
        "",
        "- METADATA_ONLY: full Description prose is never copied; at most the",
        "  first sentence (<=200 chars) is kept as a marked excerpt.",
        "- A report severity is only recorded when the report itself stated",
        "  one. The harvest's HIGH/MEDIUM listing filter is Solodit's triage,",
        "  not the auditor's claim, and is never used to infer severity.",
        "- `verified_patch` is false on every row: no fix was executed.",
        "",
    ]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    want = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != want:
            print("STALE Vbeta/reports_vbeta/solodit_ingestion_report.md "
                  "-- run: python Vbeta/scripts/build_solodit_report.py")
            return 1
        print("solodit_ingestion_report.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(want.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())